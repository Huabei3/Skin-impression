function y=cal_y(a,labs,method)
    if strcmp(method,"ellipsoidfit3_1")%cherry
    y = (1./(1+a(8)*exp(sqrt(a(1)*(labs(:,1)-a(5)).^2+a(2)*(labs(:,2)-a(6)).^2+ ...
        a(3)*(labs(:,3)-a(7)).^2+a(4)*(labs(:,2)-a(6)).*(labs(:,3)-a(7)))))).*...
    ((a(1)*(labs(:,1)-a(5)).^2+a(2)*(labs(:,2)-a(6)).^2+a(3)*(labs(:,3)-a(7)).^2+ ...
    a(4)*(labs(:,2)-a(6)).*(labs(:,3)-a(7)))>=0);
    elseif strcmp(method,"ellipsoidfit5")%summer
    y = (1./(1+exp(a(1)*sqrt((labs(:,2)-a(5)).^2+a(2)*(labs(:,3)-a(6)).^2+ ...
        a(3)*(labs(:,2)-a(5)).*(labs(:,3)-a(6)))-a(4)))).*(((labs(:,2)-a(5)).^2+ ...
        a(2)*(labs(:,3)-a(6)).^2+a(3)*(labs(:,2)-a(5)).*(labs(:,3)-a(6)))>=0);
    elseif strcmp(method,"ellipsoidfit4")%david
    y = (1./(1+exp(a(1)*sqrt(max((labs(:,1)-a(5)).^2 + a(2)*(labs(:,2)-a(6)).^2 + a(3)*(labs(:,3)-a(7)).^2 + a(4)*(labs(:,2)-a(6)).*(labs(:,3)-a(7)), 0)) - a(8)))).*...
        (((labs(:,1)-a(5)).^2 + a(2)*(labs(:,2)-a(6)).^2 + a(3)*(labs(:,3)-a(7)).^2 + a(4)*(labs(:,2)-a(6)).*(labs(:,3)-a(7))) >= 0);
    end
end