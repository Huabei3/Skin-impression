% Predict white points for each jpg in source folder (script, not function)
clc; clear; close all;

% ===== Path settings (align with find_ave) =====
baseFolder = "D:\work\ZJU_entire_skin\ZJU_skin_database\A_images\David\rendered_imgs";
sourceFolder = fullfile(baseFolder, "ori");
maskFolder = fullfile(baseFolder, "mask");

imgFiles = dir(fullfile(sourceFolder, "skin_*.jpg"));
if isempty(imgFiles)
    error('No skin_*.jpg found in: %s', sourceFolder);
end

idx_img = [1, 5, 7, 9, 10, 2, 3, 4, 6, 8];
file_names = strings(numel(idx_img), 1);
XYZw_white = nan(numel(idx_img), 3);

for i = 1:numel(idx_img)
    baseName = sprintf("skin_%d", idx_img(i));
    imgPath = fullfile(sourceFolder, strcat(baseName, ".jpg"));
    maskPath = fullfile(maskFolder, strcat(baseName, "_mask.jpg"));

    if ~exist(imgPath, 'file')
        fprintf('Image not found, skip: %s\n', imgPath);
        continue;
    end

    img_ = imread(imgPath);
    img_ = im2double(img_);
    img_ = imresize(img_, [size(img_, 1) / 2, size(img_, 2) / 2]);

    sz = size(img_);
    img = reshape(img_, [sz(1) * sz(2), 3]);

    % Optional mask (same naming as find_ave); if missing, use all pixels
    if exist(maskPath, 'file')
        mask = imread(maskPath);
        if ndims(mask) == 3
            mask = mask(:, :, 1);
        end
        mask = imresize(mask, [sz(1), sz(2)], 'nearest');
        mask = reshape(mask, [sz(1) * sz(2), 1]);
        valid = (mask == 255); % align with find_ave's ROI
    else
        valid = true(sz(1) * sz(2), 1);
    end

    if ~any(valid)
        fprintf('No valid pixels, skip: %s\n', imgFiles(i).name);
        continue;
    end

    % Gray-world white balance: use mean RGB as illuminant estimate
    meanRGB = mean(img(valid, :), 1);
    XYZw_white(i, :) = srgb2xyz(meanRGB .* 255);
    XYZw_white_cell{i,1}=XYZw_white(i, :);
    XYZw_white_cell{i,2}=strcat(baseName, ".jpg");
    file_names(i) = strcat(baseName, ".jpg");
end

% ===== Save results to a .m file =====
outDir = fileparts(mfilename('fullpath'));
if isempty(outDir)
    outDir = pwd;
end
outFile = fullfile(outDir, 'white_points.m');

fid = fopen(outFile, 'w');
if fid < 0
    error('Failed to open output file: %s', outFile);
end

fprintf(fid, '%% Auto-generated by find_white.m on %s\n', datestr(now));
fprintf(fid, 'white_points = containers.Map(''KeyType'',''char'',''ValueType'',''any'');\n');

for i = 1:numel(file_names)
    if strlength(file_names(i)) == 0 || any(isnan(XYZw_white(i, :)))
        continue;
    end
    key = char(file_names(i));
    key = strrep(key, '''', '''''');
    fprintf(fid, 'white_points(''%s'') = [%0.6f %0.6f %0.6f];\n', ...
        key, XYZw_white(i, 1), XYZw_white(i, 2), XYZw_white(i, 3));
end

fclose(fid);
fprintf('Saved white points to: %s\n', outFile);
