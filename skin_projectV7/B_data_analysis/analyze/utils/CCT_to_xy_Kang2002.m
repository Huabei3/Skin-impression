function [xy] = CCT_to_xy_Kang2002(CCT)
% CCT_TO_XY_KANG2002 计算给定相关色温(CCT)对应的CIE xy色度坐标
% 使用Kang et al. (2002)方法
% 输入:
%   CCT - 相关色温，单位为开尔文(K)
% 输出:
%   xy - CIE xy色度坐标 [x, y]

    % 检查CCT是否在有效范围内
    if any(CCT < 1667 | CCT > 25000)
        warning('相关色温应在[1667, 25000]K范围内，可能会产生不可预测的结果！');
    end
    
    % 初始化输出数组
    xy = zeros([size(CCT,1),2]);
    
    % 对每个CCT值进行处理
    for i = 1:numel(CCT)
        cct = CCT(i);
        
        % 计算x值
        if cct <= 4000
            x = -0.2661239 * 10^9 / cct^3 ...
                - 0.2343589 * 10^6 / cct^2 ...
                + 0.8776956 * 10^3 / cct ...
                + 0.179910;
        else
            x = -3.0258469 * 10^9 / cct^3 ...
                + 2.1070379 * 10^6 / cct^2 ...
                + 0.2226347 * 10^3 / cct ...
                + 0.24039;
        end
        
        % 计算y值
        if cct <= 2222
            y = -1.1063814 * x^3 ...
                - 1.34811020 * x^2 ...
                + 2.18555832 * x ...
                - 0.20219683;
        elseif cct <= 4000
            y = -0.9549476 * x^3 ...
                - 1.37418593 * x^2 ...
                + 2.09137015 * x ...
                - 0.16748867;
        else
            y = 3.0817580 * x^3 ...
                - 5.8733867 * x^2 ...
                + 3.75112997 * x ...
                - 0.37001483;
        end
        
        xy(i,:) = [x, y];
    end
end